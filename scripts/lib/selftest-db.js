#!/usr/bin/env node
/**
 * scripts/lib/selftest-db.js
 * **بيتٌ واحدٌ يحكم: أيُشغَّلُ الفخُّ الآن، أم يُعلَنُ تخطّيه؟**
 * ---------------------------------------------------------------------------
 * ═══ الحادثةُ التى وُلد منها هذا البيت — v3.75.80 ═══
 *
 * سُئل: لماذا لم يُنشَرْ إصدارُ v3.75.78 على Vercel؟ فتبيَّن أنّ حدثَ الدفعِ
 * ضاعَ مرّةً واحدة. لكنّ البحثَ كشفَ ما هو أخطرُ منه بكثير: وظيفةُ الحراسةِ
 * على GitHub (`AI Governance Audit`) **كانت حمراءَ فى كلِّ قيدٍ منذ شهور**،
 * وسببُها سطرٌ واحدٌ فى فخٍّ ذاتىٍّ واحد:
 *
 *     X PRODUCTION_SUPABASE_DB_URL is not set - cannot prove the guard refuses anything.
 *     Error: Process completed with exit code 1.
 *
 * ولأنّ وظيفةَ النشرِ فى نفسِ الملفِّ مشروطةٌ بها (`needs:`)، صارت **مُتخطّاةً
 * فى كلِّ قيد**. أى أنّ نصفَ آلةِ الحراسةِ كان مُطفأً، **ولم يقلْ ذلك أحد**.
 *
 * ═══ والعطبُ ليس فى الفخِّ بل فى انقسامِ الحكم ═══
 *
 * قِيست الفخاخُ الستّةُ والعشرونَ كلُّها بلا رابطِ قاعدة، فإذا هى **فرقتان
 * متناقضتان على نفسِ الحالةِ بعينِها**:
 *
 *   • تسعةٌ تقول «! skipping» وتخرجُ بصفر.
 *   • وتسعةٌ تقول «X cannot prove» وتخرجُ بواحد.
 *   • وثمانيةٌ لا تحتاجُ قاعدةً أصلاً.
 *
 * **وحكمانِ متناقضانِ على حالةٍ واحدةٍ ليسا اجتهاداً بل بيتَين.** فمن أخذَ
 * بالأوّلِ مرَّ صامتاً، ومن أخذَ بالثانى أسقطَ البناءَ كلَّه — والحالةُ هى هى.
 *
 * ═══ والحكمُ الصحيحُ ثالثٌ لا أوّلُ ولا ثانٍ ═══
 *
 * فخٌّ بلا قاعدةٍ **لم يُثبتْ أنّ الحارسَ يعمل، ولم يُثبتْ أنّه مكسور**. فلا
 * يجوزُ أن يقولَ «نجحتُ» (فيُخفى تعطُّلَه)، ولا أن يقولَ «سقطتُ» (فيتّهمَ
 * برىئاً ويُغرىَ صاحبَه بتخطّيه — ودرسُ v3.75.29 مكتوبٌ فى `live-db.js`:
 * **وحارسٌ يرفضُ البرىءَ يُغرى صاحبَه بتخطّيه**).
 *
 * فيقولُ الحقَّ: **لم يُقَسْ شىء** — بسطرٍ موسومٍ يُعَدُّ ولا يُنسى:
 *
 *     ! SELFTEST_SKIPPED <اسم الفخّ> — <المتغيّر> غائب: لم يُقَسْ شىء…
 *
 * ═══ ولا يصيرُ التسامحُ ثغرة ═══
 *
 * **ومكسبٌ لا يُثبَّتُ يُلتَفُّ عليه.** فللتخطّى ثمنُه:
 *
 *   (١) `--require-db` (أو `ERB_SELFTEST_REQUIRE_DB=1`) يُلغى التخطّىَ
 *       تماماً: غيابُ الرابطِ يصيرُ سقوطاً بحالةِ ١. وهذا ما يُشغَّلُ به الفخُّ
 *       على جهازٍ فيه المفاتيحُ فعلاً.
 *   (٢) والسطرُ الموسومُ **معدودٌ**: حارسُ
 *       `check-selftest-traps-have-one-home.js` يُثبِّتُ كم فخّاً يحتاجُ قاعدةً
 *       وأىَّ متغيّرٍ يسألُ — فلا ينامُ فخٌّ صامتاً ولا يُنزَعُ سؤالُه.
 *
 * **ولا يُنادى اسمٌ يسكنُه غيرُه**: الحكمُ هنا وحدَه، ولا يُنسَخُ فى فخّ.
 * ---------------------------------------------------------------------------
 */
"use strict"

const path = require("path")

/** الوسمُ الذى يُعَدُّ به التخطّى. **وما لا يُعَدُّ لا يُحرَس.** */
const SKIP_TAG = "SELFTEST_SKIPPED"

/** أسماءُ روابطِ القواعدِ التى تسألُ عنها الفخاخ — بيتُ الأسماءِ الواحد. */
const DB_URL_VARS = ["PRODUCTION_SUPABASE_DB_URL", "TEST_SUPABASE_DB_URL"]

/**
 * هل يُلزَمُ الفخُّ بالقياسِ فلا يُقبَلُ منه تخطٍّ؟
 * يُقرَأُ من الأمرِ ومن البيئةِ معاً — فسكربتُ الإصدارِ يمرّرُ العَلَم،
 * والتشغيلُ الآلىُّ يضبطُ المتغيّر.
 * @param {string[]=} argv
 */
function isRequired(argv) {
  const args = Array.isArray(argv) ? argv : process.argv.slice(2)
  if (args.includes("--require-db")) return true
  const env = String(process.env.ERB_SELFTEST_REQUIRE_DB || "").trim()
  return env === "1" || env.toLowerCase() === "true"
}

/** اسمُ الفخِّ كما يُعرَفُ به فى العدّ: اسمُ ملفِّه بلا امتداد. */
function trapName() {
  const f = process.argv[1] ? path.basename(process.argv[1]) : "(فخٌّ بلا اسم)"
  return f.replace(/\.js$/, "")
}

/**
 * يُعيدُ قيمةَ رابطِ القاعدةِ إن وُجد. وإن غاب:
 *
 *   • مع الإلزام  ⇐ يُطبَعُ سببُ السقوطِ ويُخرَجُ بحالةِ **١**.
 *   • بلا إلزام   ⇐ يُطبَعُ السطرُ الموسومُ ويُخرَجُ بحالةِ **٠**.
 *
 * **ولا يعودُ من هنا إلّا برابطٍ حقيقىّ** — فلا يقرأُ نادِيه فراغاً ويُسمّيه رابطاً.
 *
 * @param {string} varName اسمُ متغيّرِ البيئة.
 * @param {string} proves ماذا كان الفخُّ سيُثبتُ لو قاس — يُقالُ فى السطرِ نفسِه.
 * @returns {string}
 */
function requireDbOrSkip(varName, proves) {
  const name = String(varName || "")
  if (!DB_URL_VARS.includes(name)) {
    // **ولا يُنادى اسمٌ يسكنُه غيرُه**: اسمٌ خارجَ بيتِ الأسماءِ خطأُ برمجةٍ لا حالةُ تشغيل.
    console.error(`X selftest-db: متغيّرٌ غيرُ معروف «${name}» — أضِفْه إلى DB_URL_VARS أوّلاً.`)
    process.exit(1)
  }
  const url = process.env[name]
  if (url) return url

  const why = String(proves || "").trim()
  if (isRequired()) {
    console.error(
      `X ${name} غائب — والفخُّ مُلزَمٌ بالقياس (--require-db).\n` +
        (why ? `  وكان سيُثبت: ${why}\n` : "") +
        "  ولا يُشحَنُ حارسٌ لم يُرَ وهو يرفض."
    )
    process.exit(1)
  }

  console.log(
    `! ${SKIP_TAG} ${trapName()} — ${name} غائب: لم يُقَسْ شىء، ولم يُبرَّأْ حارس.` +
      (why ? ` (وكان سيُثبت: ${why})` : "")
  )
  process.exit(0)
}

module.exports = { requireDbOrSkip, isRequired, trapName, SKIP_TAG, DB_URL_VARS }
