/**
 * repo-code-files.js — **بيتٌ واحدٌ يقولُ ما هى شيفرةُ المشروع.**
 * ---------------------------------------------------------------------------
 * v3.75.35 — **وجَردٌ يقيسُ القرصَ يقيسُ جهازاً لا مشروعاً.**
 *
 * ═══ الحادثةُ التى وُلد منها هذا البيت ═══
 *
 * فى v3.75.34 صُحِّح جردُ الحارسِ فصارَ يمشى على المجلّدِ كلِّه بدل أربعةِ
 * مجلّداتٍ مكتوبةٍ باليد. ثمّ شُغِّل عندَ صاحبِ المشروعِ فقال:
 *
 *     ملفّاتُ كودٍ مسحت: 1363
 *
 * وكان الرقمُ على نسخةٍ نظيفةٍ من المستودع **1236**. الفرقُ **مئةٌ وسبعةٌ
 * وعشرونَ ملفّاً موجودةً على جهازِه وليست فى المستودع**.
 *
 * **ولم يتغيّرِ الحكمُ يومَها**: قِيس ١٩٩ على النسختَين. **لكنّ الاحتمالَ قائم**:
 * لو حملَ ملفٌّ محلىٌّ غيرُ مرفوعٍ نداءَ دالّةٍ، لَعُدَّت **مطروقةً على جهازٍ
 * ويتيمةً على جهازٍ آخَر** — فيصيرُ الحكمُ صفةَ الجهازِ لا صفةَ المشروع. وذلك
 * أخطرُ من الخطأ نفسِه، لأنّه **يمرُّ عندَ من يدفعُ ويسقطُ عندَ من يراجع**.
 *
 * ═══ فالجردُ يُقرأُ من المستودعِ لا من القرص ═══
 *
 * `git ls-files` هو **البيتُ الوحيدُ الذى يعرفُ ما هو من المشروع**: يقولُ ما فى
 * الفهرسِ — أى ما رُفع **وما رُحِّلَ للتوّ**. وسكربتُ الدفعِ يُرحّلُ ملفّاتِ
 * الدفعةِ الجديدةَ **قبلَ أن يشغّلَ الحراس**، فالشاشةُ التى وُلدت اليومَ داخلةٌ
 * فى الجرد، والملفُّ الذى يخصُّ جهازاً واحداً خارجٌ منه.
 *
 * ═══ وفحصٌ يمكن تخطّيه ليس فحصاً ═══
 *
 * إن لم يجبْ `git`، أو أعادَ قائمةً فارغة، **يُرفَعُ خطأٌ ولا تُعادُ قائمةٌ
 * فارغة**. لأنّ القائمةَ الفارغةَ تجعلُ كلَّ بابٍ يتيماً وكلَّ مخالفةٍ غائبة —
 * **والطمأنينةُ الكاذبة أسوأُ من الغياب**.
 * ---------------------------------------------------------------------------
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const repoRoot = path.join(__dirname, "..", "..");

/** امتداداتُ الشيفرةِ التى تجرى فى المتصفّحِ أو فى خادمِ التطبيق. */
const CODE_EXT = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);

/**
 * **الجردُ يشملُ المشروعَ كلَّه بالافتراض، ويُستثنى ما يُسمَّى بسببٍ مكتوب.**
 *
 * القائمةُ المكتوبةُ باليدِ كانت يوماً قائمةَ **المشمول** (`app`, `lib`,
 * `components`, `hooks`) — فسقطَ `actions/` منها صامتاً، وكادت أربعُ دالّاتٍ
 * للقوائمِ الماليّةِ تُعَدُّ يتيمةً وتُنزَعُ منحتُها (v3.75.34). **فقُلبت**:
 * أىُّ مجلّدٍ جديدٍ داخلٌ تلقائيّاً، ولا يخرجُ إلّا من يُسمَّى هنا.
 *
 * ولا يُستثنى إلّا ما **لا يجرى بحقِّ المستخدِمِ المسجَّل**. وخطأُ الشمولِ يوسّعُ
 * الجردَ فيتركُ باباً معدوداً مطروقاً، وخطأُ النقصِ يدعو إلى نزعِ منحةٍ حيّة —
 * **والميلُ الصحيحُ إلى تركِ البابِ مفتوحاً لا إلى إغلاقِه على برىء**.
 */
const NOT_SHIPPED = new Set([
  "node_modules", // ليس من المشروع
  "scripts",      // تجرى بمفتاح الخدمة (service_role) لا بحقِّ المستخدِم
  "tests",        // لا تُشحَن
  "scratch",      // لا يُشحَن
  "archive",      // لا يُشحَن
  "supabase",     // هجراتٌ ودوالُّ حافّةٍ تجرى بمفتاح الخدمة
  "docs",
  "knowledge",
  "governance",
  "ops",
]);

/**
 * هل هذا المسارُ (نسبةً إلى جذرِ المستودع، بفواصلَ أماميّة) من شيفرةِ المشروع؟
 * **دالّةٌ خالصةٌ تُختبَرُ بلا قرصٍ ولا git.**
 */
function keepPath(rel, notShipped) {
  const skip = notShipped || NOT_SHIPPED;
  const p = String(rel || "").replace(/\\/g, "/");
  if (!p) return false;
  const parts = p.split("/");
  if (parts.some((s) => s.startsWith("."))) return false; // مجلّداتٌ وملفّاتٌ مخفيّة
  if (skip.has(parts[0])) return false;
  return CODE_EXT.has(path.extname(p));
}

/** كلُّ ما يعرفُه المستودعُ من مسارات (الفهرس: المرفوعُ والمُرحَّلُ للتوّ). */
function listTrackedPaths(cwd) {
  let out;
  try {
    out = execFileSync("git", ["ls-files", "-z"], {
      cwd: cwd || repoRoot,
      maxBuffer: 128 * 1024 * 1024,
    }).toString("utf8");
  } catch (e) {
    throw new Error(
      "لم يُجبْ git ls-files — لا يُقاسُ مشروعٌ لا يُعرَفُ محتواه: " +
        String((e && e.message) || e)
    );
  }
  return out.split("\0").filter(Boolean);
}

/**
 * ملفّاتُ شيفرةِ المشروعِ بمحتواها: `[{ rel, src }]`.
 *
 * **يرفعُ خطأً ولا يُعيدُ فراغاً** إن لم يجدْ ملفّاً واحداً — فالفراغُ يجعلُ كلَّ
 * بابٍ يتيماً وكلَّ مخالفةٍ غائبة.
 *
 * والملفُّ المُسجَّلُ فى الفهرسِ والمحذوفُ من القرصِ (حذفٌ لم يُرحَّلْ بعد) يُتخطّى
 * ويُعَدّ، ويُعرَضُ عددُه فى `skipped` — **معدودٌ لا مسكوتٌ عنه**.
 */
function projectCodeFiles(options) {
  const opts = options || {};
  const cwd = opts.cwd || repoRoot;
  const paths = listTrackedPaths(cwd).filter((p) => keepPath(p, opts.notShipped));
  const files = [];
  const skipped = [];
  for (const rel of paths) {
    try {
      files.push({ rel, src: fs.readFileSync(path.join(cwd, rel), "utf8") });
    } catch {
      skipped.push(rel);
    }
  }
  if (files.length === 0) {
    throw new Error(
      "لم أقرأْ ملفَّ شيفرةٍ واحداً من المستودع — لا يُحكَمُ على ما لم يُبحَثْ فيه."
    );
  }
  return { files, skipped };
}

module.exports = { CODE_EXT, NOT_SHIPPED, keepPath, listTrackedPaths, projectCodeFiles, repoRoot };
