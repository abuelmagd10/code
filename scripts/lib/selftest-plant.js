/**
 * يزرعُ `to` مكانَ `from` فى `src`، **ويرفضُ أن يمرَّ بلا أثر**.
 *
 * @param {string} src   النصُّ الحىُّ (تعريفُ دالّةٍ من الكتالوج، أو محتوى ملفّ).
 * @param {string|RegExp} from الموضعُ المطلوب.
 * @param {string} to    ما يحلُّ محلَّه.
 * @param {string} what  وصفُ الزرعِ بلغةِ صاحبِه، ليُقرأَ فى الصياح.
 * @returns {string} النصَّ بعدَ الزرع.
 */
function plantedText(src, from, to, what) {
  if (typeof src !== "string") {
    throw new Error(`الزرعُ يحتاجُ نصّاً حيّاً: ${what} — لم يصلْ نصٌّ أصلاً.`)
  }
  // ولا يُفسَّرُ `$` فى البديل: دالّةٌ لا نصّ.
  const out = src.replace(from, () => to)
  if (out === src) {
    throw new Error(
      `الزرعُ لم يقعْ: ${what} — الموضعُ المطلوبُ (${describe(from)}) ` +
      `غيرُ موجودٍ فى النصِّ الحىّ، فلم يُزرعْ شىءٌ ولم يُثبَتْ شىء. ` +
      `الخللُ فى الفخِّ لا فى الحارس: صحِّحِ الموضعَ ثم أعِدْ.`)
  }
  return out
}

/** ينزعُ `from` من `src` نزعاً مُثبَتاً — وجهٌ آخرُ لنفسِ الحكم. */
function strippedText(src, from, what) {
  return plantedText(src, from, "", what)
}

/** وصفٌ قصيرٌ للموضعِ يصلحُ للصياح، ولا يُغرِقُ الشاشةَ بجسدِ دالّة. */
function describe(from) {
  const s = from instanceof RegExp ? String(from) : String(from)
  const one = s.replace(/\s+/g, " ").trim()
  return one.length > 90 ? `${one.slice(0, 87)}…` : one
}

module.exports = { plantedText, strippedText, describe }
