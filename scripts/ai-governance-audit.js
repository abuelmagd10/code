    add("HIGH", "Service-role route without detected permission check", `${routeUrl(f.file)} uses service-role/admin access with auth/system marker but no detected permission marker.`, f.file, 1, "Route may be authenticated but still broader than intended for role-level access.", "Gate with secureApiRequest + requirePermission or a narrowly scoped owner/admin/role check before service-role reads/writes.", "security");
