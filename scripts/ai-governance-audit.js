// Import graph and cycles
const graph = new Map(fileData.map((f) => [f.file, f.imports.filter((d) => byFile.has(d))]));
const cycles = [];
const stack = [];
const state = new Map();
function dfs(node) {
  state.set(node, "visiting");
  stack.push(node);
  for (const dep of graph.get(node) || []) {
    if (state.get(dep) === "visiting") {
      const idx = stack.indexOf(dep);
      if (idx >= 0) {
        const cycle = stack.slice(idx).concat(dep);
        const key = cycle.map(rel).join(">");
        if (!cycles.some((c) => c.key === key)) cycles.push({ key, cycle });
      }
    } else if (!state.has(dep)) dfs(dep);
  }
  stack.pop();
  state.set(node, "done");
}
for (const node of graph.keys()) if (!state.has(node)) dfs(node);
for (const c of cycles.slice(0, 25)) {
  add("HIGH", "Circular dependency", c.cycle.map(rel).join(" -> "), c.cycle[0], 1, "Can create brittle initialization order and hidden coupling.", "Break the cycle by extracting shared types/helpers into a lower-level module.", "architecture");
}

