const ensureDir = (dir) => fs.mkdirSync(dir, { recursive: true });
const rel = (file) => path.relative(root, file).replace(/\\/g, "/");
const read = (file) => fs.readFileSync(file, "utf8");
const write = (name, body) => {
  ensureDir(outDir);
  fs.writeFileSync(path.join(outDir, name), body.replace(/\r?\n/g, "\n"), "utf8");
};
const hash = (text) => crypto.createHash("sha1").update(text).digest("hex").slice(0, 12);

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ignoredDirs.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const allFiles = appCodeRoots.flatMap((d) => walk(path.join(root, d))).filter((file) => sourceExt.has(path.extname(file)));
const markdownLink = (file, line) => `[${rel(file)}](${rel(file)}${line ? `:${line}` : ""})`;

function countMatches(text, regex) {
  return (text.match(regex) || []).length;
}

function lineOf(text, needle) {
  const idx = text.indexOf(needle);
  if (idx < 0) return 1;
  return text.slice(0, idx).split(/\r?\n/).length;
}

function normalizeCode(text) {
  return text
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/.*$/gm, "")
    .replace(/(['"`])(?:\\.|(?!\1).)*\1/g, "S")
    .replace(/\b\d+(?:\.\d+)?\b/g, "N")
    .replace(/\s+/g, " ")
    .trim();
}

function extractImports(file, source) {
  const specs = [];
  for (const m of source.matchAll(/import\s+(?:type\s+)?(?:[\s\S]*?\s+from\s+)?["']([^"']+)["']/g)) specs.push(m[1]);
  for (const m of source.matchAll(/export\s+[\s\S]*?\s+from\s+["']([^"']+)["']/g)) specs.push(m[1]);
  for (const m of source.matchAll(/require\(["']([^"']+)["']\)/g)) specs.push(m[1]);
  return specs.map((spec) => resolveImport(file, spec)).filter(Boolean);
}

function resolveImport(fromFile, spec) {
  if (!spec.startsWith(".") && !spec.startsWith("@/")) return null;
  const base = spec.startsWith("@/") ? path.join(root, spec.slice(2)) : path.resolve(path.dirname(fromFile), spec);
  const candidates = [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    `${base}.js`,
    `${base}.jsx`,
    path.join(base, "index.ts"),
    path.join(base, "index.tsx"),
  ];
  return candidates.find((p) => fs.existsSync(p) && fs.statSync(p).isFile()) || null;
}

function routeUrl(file) {
  return rel(file).replace(/^app\/api/, "/api").replace(/\/route\.ts$/, "").replace(/\[([^\]]+)\]/g, ":$1");
}

function pageUrl(file) {
  const url = rel(file).replace(/^app/, "").replace(/\/page\.tsx$/, "").replace(/\[([^\]]+)\]/g, ":$1");
  return url || "/";
}

function table(rows, cols) {
  if (!rows.length) return "_No findings generated by this audit._";
  return [
    `| ${cols.join(" | ")} |`,
    `| ${cols.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${cols.map((c) => String(row[c] ?? "").replace(/\n/g, "<br>")).join(" | ")} |`),
  ].join("\n");
}

const fileData = allFiles.map((file) => {
  const source = read(file);
  const lines = source.split(/\r?\n/);
  const imports = extractImports(file, source);
  return {
    file,
    path: rel(file),
    source,
    lines: lines.length,
    imports,
    ext: path.extname(file),
    isRoute: /app\/api\/.*\/route\.ts$/.test(rel(file)),
    isPage: /app\/.*\/page\.tsx$/.test(rel(file)),
    isComponent: rel(file).startsWith("components/") || (/\.tsx$/.test(file) && /<[A-Za-z]/.test(source)),
    isHook: rel(file).startsWith("hooks/") || /export\s+function\s+use[A-Z]/.test(source),
    isService: rel(file).includes("/services/") || /class\s+\w+Service|service\.ts$|service\.tsx$/.test(rel(file)),
    isType: rel(file).startsWith("types/") || /export\s+(interface|type)\s+/.test(source),
  };
});

