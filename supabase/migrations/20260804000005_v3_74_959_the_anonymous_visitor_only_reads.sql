-- v3.74.959 — الزائرُ المجهول يقرأ ولا يكتب
-- ============================================================================
-- المقيسُ على هذه القاعدة قبل التنفيذ: الدورُ anon — وهو هويةُ كلِّ طلبٍ
-- غيرِ مسجَّلِ الدخول — يملك على مخطَّط public:
--     INSERT على ٢٦٦ · UPDATE على ٢٦٥ · DELETE على ٢٦٥
--     TRUNCATE و TRIGGER و REFERENCES على ٢٧٦ · SELECT على ٢٧٥
--
-- وليس مُستغَلّاً اليوم، وقد قِيس ذلك لا ظُنّ: صفرُ جدولٍ يمنح anon قراءةً
-- بلا حمايةِ صفوفٍ وسياسات، وسياساتُ الكتابة كلُّها تمرّ بدوالَّ تسأل عن
-- هوية المستخدم (can_modify_data، is_owner_or_admin، …) فتردّ المجهول.
--
-- لكنّ TRUNCATE **لا تخضع لحمايةِ الصفوف أصلاً**: من ملكها أفرغ الجدولَ كلَّه
-- بلا سؤال. وهى غيرُ قابلةٍ للنداء عبر PostgREST اليوم — فالبابُ مغلقٌ بقفلٍ
-- خارجىٍّ لا بقفلِه هو. وإذنٌ لا يُستعمل ليس كرماً بل دَينٌ ينتظر ساعتَه.
--
-- فتُسحب أفعالُ الكتابة كلُّها من الزائر المجهول، وتبقى القراءةُ كما هى —
-- فهى محميّةٌ بحمايةِ الصفوف، وقد قِيست.
--
-- و«ALL TABLES» فى PostgreSQL تشمل العروضَ والعروضَ المجسَّدة، وهو المقصود:
-- على الاختبار بقيت ٣٦ عرضاً تحمل الإذنَ حين مرّت المحاولةُ الأولى على
-- الجداول وحدَها.
--
-- النتيجةُ بعد التنفيذ على الإنتاج:
--     anon           → SELECT وحدَها على ٢٧٥ كائناً، ولا شىءَ غيرها
--     authenticated  → كما كان بلا نقص (٢٧٩ إدراج · ٢٧٧ تعديل · ٢٧٧ حذف)
--     service_role   → كما كان (٢٩٦ فى كلِّ فعل)
-- وأمرُ شراءٍ أُنشئ بهوية مسئول المشتريات بعدها فنجح (PO-0010، ثمّ أُرجع).
-- ============================================================================

REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
  ON ALL TABLES IN SCHEMA public FROM anon;

-- ولا يرثها ما يُنشأ غداً.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON TABLES FROM anon;
