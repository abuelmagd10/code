-- ============================================================================
-- v3.74.824 — قيود التصنيع كانت تُولد ميتة (draft) ولا تُرحَّل أبداً
-- ============================================================================
-- **أخطر ما كُشف فى مراجعة التقارير الاسترشادية**، ووصل إليه الخيط من سؤال
-- بسيط: لماذا يوجد قيدان بحالة «مسودة» فى قاعدة الإنتاج؟
--
-- **الفجوة**: `createEntryHeader` فى `lib/manufacturing/manufacturing-accounting.ts`
-- تُنشئ القيد بحالة `'draft'`، **ولم يكن فى الملف كله سطر واحد يحوّله إلى
-- `'posted'`**. فكل قيود التصنيع تُولد ميتة:
--   • **صرف المواد للإنتاج لا يدخل الدفاتر إطلاقاً.**
--   • **استلام المنتج التام لا يدخل الدفاتر إطلاقاً.**
-- بينما دفعات FIFO والمخزون الفعلى يتحركان كالمعتاد — والدالة تُرجع
-- `success: true` فلا يشك أحد.
--
-- **ولماذا بدت الدورة التجريبية سليمة؟** لأن حارساً قديماً كان يُرحّل قيد
-- الاستلام بالتوازى (JE-000056). وفى 814 أسقطناه بوصفه «ازدواجاً» وعكسنا
-- قيده — وهو فى الحقيقة كان **المُرحِّل الوحيد**. صحّت الأرصدة بالمصادفة
-- وحدها: صرف مواد 60 لم يُرحَّل، واستلام 60 رُحّل ثم عُكس ⇒ الصافى صفر،
-- وهو نفس صافى الدورة الصحيحة **لأن تكلفة التحويل كانت صفراً**. مع أول
-- مركز عمل بسعر حقيقى (بعد 818) كان الفارق سيظهر انحرافاً دائماً.
--
-- **العلاج (فى الكود)**: دالة `postEntryHeader` تُرحّل القيد بعد إدراج
-- سطوره، وتتحقق من التوازن **من قاعدة البيانات** لا من المصفوفة فى الذاكرة،
-- وتتراجع عن القيد بالكامل إن اختل — فلا رأس قيد يتيم ولا قيد مشوَّه.
--
-- **العلاج (فى التقارير)**: أربعة تقارير محاسبية كانت تستثنى القيود المحذوفة
-- **ولا تفلتر الحالة** ⇒ المسودات تتسرب إلى الأرصدة:
--   • `bank-accounts-by-branch` — أرصدة البنوك.
--   • `update-account-balances` — وهذه **تكتب** الأرصدة المخزَّنة!
--   • `fx-gains-losses` — أرباح وخسائر فروق الصرف.
--   • `bank-transactions` — كشف حركة البنك (بلا أى فلتر حالة).
-- أُضيف `status='posted'` و`is_deleted` لكلٍّ منها.
--
-- **إصلاح البيانات**: المسودتان العالقتان (MFG-ISSUE و MFG-RECV) أُلغيتا
-- (is_deleted) مع توثيق السبب داخل وصف القيد نفسه: أثر الدورة مُثبت بالفعل
-- عبر JE-000056/57، فترحيلهما الآن يضاعف.
--
-- **التحقق بعده**: صفر مسودات حية · ميزان المراجعة **0.00** ·
-- المخزون **140.77** = تقييم الدفعات **140.77** ✓
--
-- ملاحظة: هذه الهجرة توثيقية — الإصلاح كله فى الكود وفى صفّى بيانات
-- أُلغيا، ولا دالة قاعدة بيانات تتغير.
-- ============================================================================

-- إلغاء أى مسودة تصنيع عالقة (يسرى على كل الشركات، وآمن التكرار)
UPDATE journal_entries
SET is_deleted = TRUE,
    deleted_at = COALESCE(deleted_at, NOW()),
    description = description ||
      ' — [v3.74.824] مسودة عالقة من بانى قيود التصنيع قبل إصلاح الترحيل.'
WHERE status = 'draft'
  AND COALESCE(is_deleted, false) = false
  AND reference_type IN ('manufacturing_material_issue', 'manufacturing_product_receipt');
