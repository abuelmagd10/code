-- ═══════════════════════════════════════════════════════════════════
-- v3.74.921 — أوامر الشراء تُعزل بالفرع
-- ═══════════════════════════════════════════════════════════════════
--
-- أولُ جدولٍ من التسعة عشر التى قِيست فى 917. واختير أوّلاً لأنه الأقرب
-- إلى عمل المالك هذه الأيام، ولأن سعر الشراء يعيش فى بنوده.
--
-- ═══════════ ما قِيس قبل الكتابة ═══════════
--
-- **فى القاعدة**: ثلاث سياسات قراءةٍ متساهلة، و**ثلاثتها على مستوى
-- الشركة** — ولا سياسةَ عزلٍ بالفرع أصلاً. وهذا يختلف عن حال الجداول
-- الأربعة فى 917: هناك كان العزل مكتوباً ومعطَّلاً بالـOR، وهنا لم يُكتب
-- قط.
--     purchase_orders_access_members  →  EXISTS(company_members …)
--     purchase_orders_select_members  →  EXISTS(company_members …)
--     purchase_orders_select          →  companies.user_id UNION company_members
--
-- **بالانتحال على الإنتاج**: كل عضوٍ يرى الثمانية، ومنها **اثنان لمدينة
-- نصر** — حتى موظف المبيعات ومسئول المخزن.
--
-- **وبابٌ نصفُ مفتوح** خلّفه 917: موظف الفرع الرئيسى يرى **رأس** أمر شراء
-- نصر (المورد والإجمالى ٩٨٦٫١٠ والحالة) و**صفر بنود** — فيفتح مستنداً بلا
-- أصناف، يقرأ الرقم الكبير ولا يرى ممّ تكوّن. ونصفُ الباب أسوأ من حاليه.
--
-- **وفى التطبيق**: الشاشتان الرئيسيتان تفلتران بالفرع بالفعل — شاشة أوامر
-- الشراء عبر `getAccessFilter`، وتقرير حالة الأوامر يقصر غير الإدارة على
-- فرعه — **وجمهور «الإدارة» عندهما هو نفسه جمهور القاعدة هنا**. فالإغلاق
-- يطابق ما تفعله الشاشات، ويحوّل فلترة الكود من الحماية الوحيدة إلى طبقةٍ
-- ثانية. وثمانية مسارات أخرى تقرأ الجدول: سبعةٌ بجلسة المستخدم (والصحيح
-- لها أن تُقيَّد بفرعه — بانى خطة التصنيع يفلتر بالفرع أصلاً)، وواحدٌ
-- بمفتاح الخدمة (إرسال أمر الشراء) لا تمسّه السياسة.
--
-- ═══════════ والقاعدة نفسها، لا قاعدةٌ جديدة ═══════════
--
-- `can_access_record_branch` كما اعتُمدت فى 917: المالك المسجَّل والأدوار
-- العامة (`owner`/`admin`/`general_manager`) وعضو الشركة **بلا فرعٍ فى
-- عضويته** بلا قيد؛ وغيرهم فرعُه وحده؛ والسجل بلا فرع للجميع.
--
-- وسياسةٌ **واحدة** تحلّ محل الثلاث: تعدّدُ السياسات المتساهلة هو نفسه
-- الذى أنتج مصيدة 917، فلا يُترك بابٌ ثانٍ ولو كان نصُّه صحيحاً اليوم.
-- ═══════════════════════════════════════════════════════════════════

DROP POLICY IF EXISTS purchase_orders_access_members ON public.purchase_orders;
DROP POLICY IF EXISTS purchase_orders_select_members ON public.purchase_orders;
DROP POLICY IF EXISTS purchase_orders_select         ON public.purchase_orders;

CREATE POLICY purchase_orders_select_branch_isolation ON public.purchase_orders
FOR SELECT
USING (
  company_id IN (SELECT get_user_company_ids())
  AND public.can_access_record_branch(company_id, branch_id)
);

COMMENT ON POLICY purchase_orders_select_branch_isolation ON public.purchase_orders IS
  'v3.74.921 — أمر الشراء يُقرأ بقيد فرعه. حلّت محل ثلاث سياساتٍ على مستوى الشركة، ولم يكن على الجدول عزلٌ بالفرع قط.';
