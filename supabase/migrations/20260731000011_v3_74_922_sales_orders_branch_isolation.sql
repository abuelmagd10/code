-- v3.74.922 — أوامر البيع تُعزل بالفرع
-- ═══════════════════════════════════════════════════════════════════
--
-- ثانى جدولٍ من التسعة عشر، وشكلُه غيرُ شكل أوامر الشراء تماماً — ولهذا
-- قِيس قبل أن يُكتب فيه حرفٌ واحد.
--
-- ═══════════ ما قِيس قبل الكتابة ═══════════
--
-- **نظام رؤيةٍ حقيقىٌّ قائمٌ هنا بالفعل**: `sales_orders_select_v4` تقرأ
-- صلاحية الدور من `company_role_permissions` ثم تقرّر: شركة · فرع ·
-- مستنداتى. وليست الحال حال أوامر الشراء فى 921 — ثلاث سياساتٍ على مستوى
-- الشركة ولا عزلَ أصلاً.
--
-- **وبالانتحال على الإنتاج** (أربعة أوامر: ثلاثةٌ للرئيسى وواحدٌ لنصر):
--     المحاسب ٠ · المدير ٣ (لا شىء من غير فرعه) · مسئول التصنيع ٠ ·
--     المالك ٤ · مسئول المشتريات ٠ · **الموظف ٤ ومنها ١ لنصر** ·
--     مدير المخزن ٠
--
-- **والبنود سليمة** — بخلاف ما وجدناه فى 917 و921: سياسةُ البند تسأل عن
-- **رأسها** لا عن عضوية الشركة، والرأس محمىٌّ بسياسته. فمن ١٩٢ بنداً فى
-- القاعدة كلِّها لا يرى مالك الشركة إلا ٤. لا بابَ هنا يُغلق.
--
-- **والكتابة تتبع القراءة**: تعديل أمر نصر بهوية المدير والمحاسب ومدير
-- المخزن ⇒ صفر صف. وتعديلٌ **بلا شرطٍ أصلاً** بهوية المدير مسّ ٣ صفوف —
-- أى فرعَه وحده. فسياسةُ القراءة هى الجدار للقراءة والكتابة معاً، لأن
-- Postgres يطبّق سياسة SELECT على الصفوف التى يقرؤها التعديل والحذف.
--
-- ═══════════ فما الذى بقى مفتوحاً ═══════════
--
-- **(١) ذراع «مستنداتى» يعبر الجدار.** موظفٌ عضوٌ فى **الفرع الرئيسى**
-- أنشأ أمر بيعٍ **لمدينة نصر**، فيراه اليوم لأنه مُنشئه، لا لأن الفرع
-- فرعُه. وفى الذراع نفسه `has_shared_access` خارج قيد الفرع — صفر مشاركةٍ
-- نشطةٍ اليوم، فهو بابٌ نائمٌ لا مفتوح.
--
-- **(٢) وسياسةٌ متساهلةٌ ثانيةٌ نائمة**: `sales_orders_company_isolation`
-- على **كل** الأوامر، شرطُها `app.current_company_id` — ولا سطرَ واحدٌ فى
-- المشروع كلِّه يضبط هذا المتغير، فهى ميّتةٌ اليوم. لكنها **مصيدةُ 917
-- نائمة**: يكفى سطرٌ يضبطه يوماً ليصير الشرطُ صادقاً، فتسقط القسمةُ
-- كلُّها بالـOR. فتُحذف الآن، لا حين تستيقظ.
--
-- ═══════════ والحكم ═══════════
--
-- نظام الرؤية **يبقى كما هو**، لا يُلغى ولا يُبدَّل: شركة · فرع ·
-- مستنداتى · مشاركة. ويُلفّ كلُّه داخل سؤالٍ أخيرٍ واحد:
-- `can_access_record_branch` — نفس القاعدة المعتمدة فى 917 و921. فالفرعُ
-- **فوق** الإنشاء والمشاركة، لا بجوارهما.
--
-- وواحدةٌ تحلّ محل اثنتين: تعدّدُ السياسات المتساهلة هو نفسه الذى أنتج
-- مصيدة 917، فلا يُترك بابٌ ثانٍ ولو كان نصُّه ميّتاً اليوم.
-- ═══════════════════════════════════════════════════════════════════

DROP POLICY IF EXISTS sales_orders_company_isolation ON public.sales_orders;
DROP POLICY IF EXISTS sales_orders_select_v4         ON public.sales_orders;

CREATE POLICY sales_orders_select_branch_isolation ON public.sales_orders
FOR SELECT
USING (
  public.is_company_member(company_id)
  AND (
       public.current_user_resource_visibility(company_id, 'sales_orders') = 'company'
    OR (public.current_user_resource_visibility(company_id, 'sales_orders') = 'branch'
        AND (branch_id IS NULL OR branch_id = public.current_user_branch_id(company_id)))
    OR (public.current_user_resource_visibility(company_id, 'sales_orders') = 'own'
        AND created_by_user_id = auth.uid())
    OR public.has_shared_access(company_id, 'sales_orders', created_by_user_id)
  )
  AND public.can_access_record_branch(company_id, branch_id)
);

COMMENT ON POLICY sales_orders_select_branch_isolation ON public.sales_orders IS
  'v3.74.922 — نظام الرؤية كما هو (شركة · فرع · مستنداتى · مشاركة) ملفوفاً داخل قيد الفرع. وحلّت أيضاً محل سياسةٍ متساهلةٍ ميّتةٍ كانت تنتظر متغيّراً لا يضبطه أحد.';
