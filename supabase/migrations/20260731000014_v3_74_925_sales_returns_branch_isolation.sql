-- ═══════════════════════════════════════════════════════════════════
-- v3.74.925 — طلبات مرتجع البيع ومرتجعاتُه تُعزل بالفرع
-- ═══════════════════════════════════════════════════════════════════
--
-- خامس جدولٍ من التسعة عشر — ومعه جارُه، كما فى 924.
--
-- ═══════════ ما قِيس قبل الكتابة ═══════════
--
-- `sales_return_requests`: سياسةُ قراءةٍ واحدة على مستوى الشركة، ولا عزلَ
-- بالفرع. وبالانتحال على الإنتاج: **الأدوار السبعة كلُّها** ترى طلبَ مرتجع
-- مدينة نصر.
--
-- **وفى الطلب نفسه شهادةٌ على القِدَم**: مُقدِّمُه هو **محاسبُ الفرع
-- الرئيسى**، والفاتورة فاتورةُ **نصر**. أى أنه رأى فاتورةَ فرعٍ ليس فرعَه
-- وطلب مرتجعَها — وهو بابٌ أُغلق فى 917، وهذا الصفُّ أثرُه الباقى.
--
-- **وجارُه `sales_returns`** (مستند المرتجع نفسه، وفيه المبالغ) — لم يكن
-- فى قائمة التسعة عشر أصلاً، وسياستُه `is_company_member` وحدها. صفر صفٍّ
-- اليوم على الإنتاج، فالبابُ يُغلق قبل أن يُفتح.
--
-- **وفى التطبيق**: مسارات الطلبات تفلتر بالفرع بالفعل
-- (`query.eq("branch_id", member.branch_id)` فى مسار القائمة وفى عدّاد
-- المعلَّقات)، فالإغلاق يطابق ما تفعله الشاشة ويصير الكودُ طبقةً ثانية.
--
-- ═══════════ وسؤال 924: ما معنى «بلا فرع» هنا؟ ═══════════
--
-- قِيس فى الكود: الطلب يأخذ فرعَه من **فاتورته**، فإن لم تكن لها فرعٌ
-- فمن **عضوية مُقدِّمه**، فإن لم يكن فـ`NULL`
-- (`invoice.branch_id || member?.branch_id || null`).
--
-- فـ«بلا فرع» هنا ليست **مستنداً مشتركاً بين فروع** كما كانت فى مرتجع
-- الشراء المتعدد المخازن، بل **بيانٌ على مستوى الشركة** لا فرعَ له أصلاً.
-- ولهذا تنطبق القاعدة المعتادة بلا تفصيل: `can_access_record_branch`
-- تُمرّره، وهو صحيح.
--
-- **وهذا هو الفرق الذى منع النسخ فى 924 ويسمح به هنا** — والسؤال يُطرح فى
-- كل جدول، ولا يُفترض جوابُه.
--
-- ═══════════ وملاحظةٌ قِيست ولم تُعالَج هنا ═══════════
--
-- على قاعدة الاختبار: **٦ صفوفٍ فى `sales_return_items` بلا مستندٍ أب**
-- (صفر `sales_returns`). لا يراها أحدٌ لأن سياستها تسأل عن رأسها، لكنها
-- صفوفٌ يتيمة. سُجّلت فى دفتر التسليم ولم تُمسّ فى دفعةٍ أمنية.
-- ═══════════════════════════════════════════════════════════════════

DROP POLICY IF EXISTS srr_select           ON public.sales_return_requests;
DROP POLICY IF EXISTS sales_returns_select ON public.sales_returns;

CREATE POLICY sales_return_requests_select_branch_isolation ON public.sales_return_requests
FOR SELECT
USING (
  company_id IN (SELECT get_user_company_ids())
  AND public.can_access_record_branch(company_id, branch_id)
);

CREATE POLICY sales_returns_select_branch_isolation ON public.sales_returns
FOR SELECT
USING (
  company_id IN (SELECT get_user_company_ids())
  AND public.can_access_record_branch(company_id, branch_id)
);

COMMENT ON POLICY sales_return_requests_select_branch_isolation ON public.sales_return_requests IS
  'v3.74.925 — طلبُ المرتجع يُقرأ بقيد فرعه. وأُضيف المالك المسجَّل الذى كانت السياسة القديمة تنساه.';
COMMENT ON POLICY sales_returns_select_branch_isolation ON public.sales_returns IS
  'v3.74.925 — مستندُ مرتجع البيع يُقرأ بقيد فرعه، وبنودُه تتبعه بسياستها القائمة (قِيس بالزرع).';
