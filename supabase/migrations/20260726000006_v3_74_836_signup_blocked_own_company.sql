-- ============================================================================
-- 🔴 v3.74.836 — عميل حقيقى لم يستطع إنشاء شركته: مالكها غريب عنها لحظة إنشائها
-- ============================================================================
-- أخطر عطب فى الجلسة كلها، لأنه يُوقف **أول شاشة يراها عميل يدفع**.
-- ما رآه العميل: «فشل في إنشاء الشركة» — ولا شىء غير ذلك.
--
-- ── السلسلة الكاملة (مُستخرَجة من سياق الخطأ فى القاعدة) ──────────────────
--   INSERT companies
--     → trg_seed_company_accounts
--        → seed_default_chart_of_accounts → sync_company_chart_of_accounts
--           → INSERT chart_of_accounts
--              → audit_trigger_function → create_audit_log
--                 → assert_company_access → RAISE «غير مصرح»
--
-- `assert_company_access` كانت تفحص `company_members` **وحده**. وصف العضوية
-- يُكتب من الواجهة **بعد** رجوع الإدراج — فطوال تلك الجملة الواحدة يكون
-- **مُنشئ الشركة غريباً عن شركته هى**، وكل مُشغِّل تهيئة يكتب سجل تدقيق يقتل
-- التسجيل. والجملة تُلغى بالكامل، فلا شركة ناقصة ولا أثر فى النظام: قناة
-- التسجيل تتوقف عن التحويل **بصمت**.
--
-- ── لماذا لم يكشفه شىء ───────────────────────────────────────────────────
-- • فحص الأنواع لا يرى منطق قاعدة البيانات.
-- • الاختبارات الحرجة لا تُنشئ شركات.
-- • وبمفتاح الخدمة (service_role) **ينجح الإدراج دائماً**، لأن `auth.uid()`
--   تكون فارغة فيرجع الفحص فوراً — فالمسار يبدو سليماً من كل لوحة تحكم.
-- • والخطأ يظهر **للشخص الأقل قدرة على الإبلاغ عنه**.
--
-- ── العلاج ───────────────────────────────────────────────────────────────
-- يُقبل أيضاً مالك الشركة المسجَّل على السجل نفسه (`companies.user_id`).
-- وهذا **ليس تخفيفاً أمنياً**: هو نفس الشخص، مُسجَّلاً فى مكان آخر — وصف
-- العضوية تكرار لواقعة مكتوبة أصلاً على صف الشركة.
--
-- ملاحظة تُصان: الرفع يستخدم ERRCODE **57014** (query_canceled) عن قصد، لأن
-- `WHEN OTHERS` فى PL/pgSQL **لا يلتقط** هذه الفئة — فلا تستطيع دالة مُنادية
-- أن تبتلع فشل تصريح بالخطأ. وأى معالج يجب أن يُسمّى `query_canceled` صريحاً.
-- (وهذا نفسه أفشل أول محاولة تحقق كتبتها: `WHEN OTHERS` لم يلتقط الخطأ.)
--
-- ── التحقق على الإنتاج (بمحاكاة مستخدم مسجَّل، ثم إلغاء) ─────────────────
--   قبل الإصلاح: «غير مصرح: هذه العملية تخص شركة أخرى» ✗
--   بعد الإصلاح: إدراج ناجح · **٩٤ حساباً · فرع واحد · مخزن واحد** ✓
--   ووصول مستخدم لا يملك الشركة ولا ينتمى لها: **مرفوض** ✓ (الأمان كما هو)
--
-- والحارس الجديد `scripts/verify-signup-path.js` يُعيد هذا الاختبار فى كل
-- نشرة وفى CI: يُنشئ شركة بهوية مستخدم حقيقى داخل معاملة ثم يُلغيها.
-- ============================================================================

CREATE OR REPLACE FUNCTION public.assert_company_access(p_company_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'pg_catalog'
AS $function$
DECLARE
  v_uid uuid := auth.uid();
BEGIN
  -- No end-user identity: server-side call (service_role / cron / internal
  -- SECURITY DEFINER caller). Authorisation happened in the API layer.
  IF v_uid IS NULL THEN
    RETURN;
  END IF;

  IF p_company_id IS NULL THEN
    RETURN;
  END IF;

  IF EXISTS (
    SELECT 1 FROM company_members
    WHERE company_id = p_company_id AND user_id = v_uid
  ) THEN
    RETURN;
  END IF;

  -- v3.74.836 — مالك الشركة المسجَّل على السجل نفسه.
  -- كان الفحص يعتمد على `company_members` وحده، فمُنشئ الشركة يُعامَل كغريب
  -- **عن شركته هى** فى اللحظة التى يُنشئها فيها: صف العضوية يُكتب بعد الإدراج،
  -- بينما مُشغِّلات التهيئة (سجل التدقيق · صلاحيات الأدوار) تعمل داخله وتنادى
  -- هذا الفحص. فسقط إنشاء الشركة على عميل حقيقى برسالة «غير مصرح».
  -- و`companies.user_id` ليس تخفيفاً: هو نفس الشخص، مُسجَّلاً فى مكان آخر.
  IF EXISTS (
    SELECT 1 FROM companies
    WHERE id = p_company_id AND user_id = v_uid
  ) THEN
    RETURN;
  END IF;

  -- 57014 (query_canceled), NOT 42501: see the note above. WHEN OTHERS
  -- handlers in the calling functions swallow 42501 and continue.
  RAISE EXCEPTION 'غير مصرح: هذه العملية تخص شركة أخرى'
    USING ERRCODE = '57014';
END;
$function$;
