-- ============================================================================
-- v3.74.838 — الشاشة تقول للعميل **حالته**، لا رسالة غامضة ولا نجاح كاذب
-- ============================================================================
-- ٨٣٧ استبدلت رسالة النجاح الكاذبة برسالة **صادقة لكن غامضة** («لو بريدك غير
-- مؤكَّد وصلك كود… ولو مؤكَّد فلن يُرسل»). والمالك راجعها فى الاستخدام وقال إن
-- المطلوب أن تُخبره **بحالته** صريحاً — والعميل نفسه ظلّ ٢٥ دقيقة يطلب كوداً
-- ولم يفتح صفحة الدخول ولا مرة (`last_sign_in_at` لم يتغير).
--
-- ── المقايضة، مذكورة صريحة ────────────────────────────────────────────────
-- ليقول النظام الحالة بثقة يجب أن يفحص البريد، فيصير ممكناً معرفة أن بريداً
-- معيّناً مسجَّل (تعداد المستخدمين). وقُلِّل الأثر بأمرين:
--   • الدالة تُرجع **حالة واحدة**: `confirmed` أو `pending`. والبريد **غير
--     الموجود** وغير المؤكَّد **لا يُفرَّق بينهما** — فالمكشوف هو الحسابات
--     المؤكَّدة وحدها، لا وجود البريد عموماً.
--   • **حدّ معدّل لكل IP** (٨/دقيقة) **داخل الدالة نفسها**، فلا يُتجاوز.
-- وقرار قبول هذه المقايضة اتخذه مالك المنتج بعد عرض البديلين عليه.
--
-- ── 🔧 تصحيح v3.74.839: المفتاح الخطأ فى المكان الخطأ ─────────────────────
-- أول تنفيذ وضع الحدّ فى مسار خادمى `POST /api/auth/email-state` يحمل **مفتاح
-- الخدمة** — أى صلاحيات كاملة على القاعدة كلها — **بلا أى مصادقة**، لأن
-- المستخدم هنا لم يُسجّل دخوله بعد. وأمسكه حارس `check-service-role-scoping`
-- فى CI محقاً: مسار عام يحمل صلاحيات كاملة **خطر قائم بذاته**، حتى لو كان
-- استعماله اليوم بريئاً — فتعديل واحد لاحق يجعله بوابة على بيانات كل الشركات.
--
-- ولم يُستثنَ من الحارس، بل **أُزيلت الحاجة إليه**: نُقل حدّ المعدّل إلى داخل
-- الدالة (يقرأ IP من `request.headers`)، فصارت تُنادى بمفتاح **anon** من
-- المتصفح مباشرة، وحُذف المسار الخادمى بالكامل. والنتيجة أفضل من الاستثناء:
--   • لا مفتاح خدمة فى مسار عام إطلاقاً.
--   • والحدّ **غير قابل للتجاوز** لأنه جزء من الدالة لا من مُناديها — بينما
--     حدّ المسار كان يُتجاوَز بمناداة الدالة مباشرة.
-- تحقق على قاعدة الاختبار: ٨ استدعاءات مسموحة، والتاسع والعاشر `unknown`.
--
-- ── تحقق على الإنتاج ─────────────────────────────────────────────────────
--   بريد العميل الحقيقى        ⇒ 'confirmed'
--   بريد لا وجود له            ⇒ 'pending'   (لا يُفرَّق عن غير المؤكَّد)
--
-- وفى الواجهة: الحالة تُفحص **عند فتح الشاشة** لا بعد الضغط على «إعادة
-- الإرسال» — فمَن حسابه مؤكَّد يعرف ذلك قبل أن يجلس ينتظر. وتُعرض لافتة خضراء
-- أعلى النموذج، ويصير زر «اذهب لتسجيل الدخول» زراً أساسياً.
-- وكل نصوص الشاشة صارت **بلغة المستخدم المختارة** (ar/en) مع اتجاه الصفحة —
-- كانت عربية ثابتة، فمَن اختار الإنجليزية يُواجَه بعربية فى أحرج شاشة.
-- ============================================================================

CREATE OR REPLACE FUNCTION public.auth_email_state(p_email text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'pg_catalog'
AS $function$
DECLARE
  v_confirmed TIMESTAMPTZ;
  v_headers   JSONB;
  v_ip        TEXT := 'unknown';
  v_limit     JSONB;
BEGIN
  -- v3.74.839 — حدّ المعدّل **داخل الدالة** لا فى مسار خادمى.
  -- كان المسار يحمل مفتاح الخدمة (صلاحيات كاملة على القاعدة كلها) بلا أى
  -- مصادقة — وحارس `check-service-role-scoping` أمسكه محقاً. ونقل الحدّ إلى
  -- هنا يُلغى الحاجة للمفتاح تماماً: تُنادى الدالة بمفتاح anon من المتصفح،
  -- والحدّ لا يمكن تجاوزه لأنه صار جزءاً من الدالة نفسها لا من مُناديها.
  BEGIN
    v_headers := NULLIF(current_setting('request.headers', true), '')::jsonb;
    v_ip := COALESCE(
      NULLIF(btrim(split_part(COALESCE(v_headers->>'x-forwarded-for', ''), ',', 1)), ''),
      NULLIF(btrim(COALESCE(v_headers->>'x-real-ip', '')), ''),
      'unknown'
    );
  EXCEPTION WHEN OTHERS THEN
    v_ip := 'unknown';
  END;

  v_limit := public.check_and_increment_rate_limit('ip:' || v_ip, 'auth_email_state', 8, 60);

  IF COALESCE((v_limit->>'allowed')::boolean, false) = false THEN
    -- لا نُفصح عن شىء عند التجاوز: الشاشة تعود لرسالتها الغامضة الصادقة.
    RETURN 'unknown';
  END IF;

  -- تُرجع حالة واحدة فقط: هل البريد **مؤكَّد**؟ والبريد غير الموجود وغير
  -- المؤكَّد **لا يُفرَّق بينهما** (كلاهما 'pending')، فالمكشوف هو الحسابات
  -- المؤكَّدة وحدها — الثمن المقصود مقابل أن يعرف العميل حالته.
  SELECT u.email_confirmed_at INTO v_confirmed
    FROM auth.users u
   WHERE lower(u.email) = lower(btrim(COALESCE(p_email, '')))
   LIMIT 1;

  IF v_confirmed IS NOT NULL THEN
    RETURN 'confirmed';
  END IF;

  RETURN 'pending';
END;
$function$;

-- تُنادى من المتصفح بمفتاح anon: الحدّ داخلها، فلا حاجة لمفتاح خدمة ولا لمسار.
REVOKE ALL ON FUNCTION public.auth_email_state(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.auth_email_state(text) TO anon, authenticated, service_role;
