-- v3.74.927 — الموردون يُقرأون بقيد الفرع (والقاعدة كانت مكتوبةً للكتابة وحدها)
-- ═══════════════════════════════════════════════════════════════════
--
-- سابع جدولٍ من التسعة عشر — وأولُ **مرجعٍ مشترك** لا مستند.
--
-- ═══════════ ما قِيس قبل الكتابة ═══════════
--
-- بالانتحال على الإنتاج: **الأدوار السبعة كلُّها** ترى موردَى مدينة نصر.
-- سياسةُ القراءة `is_company_member(company_id)` — لا فرعَ فيها.
--
-- **لكنّ الكتابة كانت مضبوطةً بالفرع منذ زمن**: `suppliers_insert` و
-- `suppliers_update` و`suppliers_delete` ثلاثتُها تسأل
-- `can_manage_supplier_row(company_id, branch_id)`، وهى دالةٌ تعرف الفرع
-- وتعرف الأدوار.
--
-- **فهذه ثالثُ مرة** فى هذه السلسلة تكون القاعدة **معروفةً فى المشروع
-- وغيرَ معمَّمة**: `booking_payments` فى 926، ودوالُّ الكتابة هنا. والدرسُ
-- واحد: القاعدةُ لا تنتشر بنفسها، والحارسُ هو الذى ينشرها.
--
-- **وفى التطبيق**: شاشة الموردين تفلتر بالفرع بالفعل (`q.eq('branch_id',
-- currentUserBranchId)`) وتترك الأدوارَ المميزة بلا قيد — وهو نفس جمهور
-- القاعدة هنا. فالإغلاق يطابق الشاشة ويحوّل فلترة الكود إلى طبقةٍ ثانية.
-- وعشرون مساراً آخر يقرأ الجدول، جلُّها بجلسة المستخدم.
--
-- ═══════════ وسؤال 924: ما معنى «بلا فرع» هنا؟ ═══════════
--
-- قِيس: الشاشة تسمح بمورّدٍ **بلا فرع** صراحةً (خيار «__none__» يُحوَّل إلى
-- `NULL`). و`can_manage_supplier_row` **ترفض** لأصحاب الفروع تعديلَ مورّدٍ
-- بلا فرع، وتسمح للأدوار العامة وحدها.
--
-- فـ«بلا فرع» هنا **مورّدٌ على مستوى الشركة**: يقرؤه الجميع، ولا يعدّله إلا
-- الإدارة. وهو ما تقوله دالةُ الكتابة القائمة، فتُتبَع القراءةُ لها بلا
-- اختراع. (وعلى الإنتاج: أربعةٌ من أربعة لها فروع، فلا صفَّ من هذا الشكل
-- اليوم.)
--
-- ═══════════ وسياستان زائدتان تُحذفان (قِيستا) ═══════════
--
-- `suppliers_owner_select` و`suppliers_owner_dml` تفتحان للمالك المسجَّل ما
-- هو مفتوحٌ له أصلاً: `can_manage_supplier_row` تبدأ بـ«المالك المسجَّل ⇒
-- صحيح» فتغطّى الإدراج والتعديل والحذف، والسياسةُ الجديدة تغطّى القراءة عبر
-- `get_user_company_ids` و`can_access_record_branch`.
--
-- وتُحذفان لأنهما **بابان متساهلان ثانيان بجوار العزل** — شكلُ مصيدة 917.
-- ولم يُكتفَ بقراءة النصوص: بُرهن بالزرع على الاختبار (فى معاملةٍ ملغاة)
-- أن المالك المسجَّل بعد حذفهما **ينشئ مورّداً ويقرؤه ويعدّله ويحذفه**.
-- ═══════════════════════════════════════════════════════════════════

DROP POLICY IF EXISTS suppliers_select        ON public.suppliers;
DROP POLICY IF EXISTS suppliers_owner_select  ON public.suppliers;
DROP POLICY IF EXISTS suppliers_owner_dml     ON public.suppliers;

CREATE POLICY suppliers_select_branch_isolation ON public.suppliers
FOR SELECT
USING (
  company_id IN (SELECT get_user_company_ids())
  AND public.can_access_record_branch(company_id, branch_id)
);

COMMENT ON POLICY suppliers_select_branch_isolation ON public.suppliers IS
  'v3.74.927 — المورّد يُقرأ بقيد فرعه، والمورّد بلا فرعٍ مورّدُ الشركة كلِّها — وهو ما كانت دالةُ الكتابة تقوله منذ زمن.';
