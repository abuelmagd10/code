-- v3.75.44-أ — «ودالّةُ زنادٍ لا تُمنَحُ لأحد»
-- ═══════════════════════════════════════════════════════════════════════════
--
-- **الحارسُ عمل، والنقصُ منّى.**
--
-- v3.75.44 وَلَدَ دالّةَ زنادٍ جديدة: `enforce_payment_reference_resolves`.
-- وPostgres يمنحُ كلَّ دالّةٍ جديدةٍ حقَّ التنفيذِ لـPUBLIC تلقائيّاً — فورثَه
-- `anon` و`authenticated`. ونُزِعَ المنحُ عن الدالّاتِ الثلاثِ الأخرياتِ فى تلك
-- الدفعةِ **ونُسِىَ عن هذه**.
--
-- فسقطَ عليها **فحصانِ مرجعيّانِ كتبَهما إصدارانِ سابقان** — v3.75.25 وv3.75.29 —
-- بنصٍّ واحد:
--
--     «دالّةُ زنادٍ ممنوحةٌ للنداءِ ولا يستطيعُ أحدٌ نداءَها
--      — زينةٌ على بابٍ لا يُفتَح»
--
-- **ولم تُدفَعِ الدفعة.** الحارسُ رأى ما لم أرَه، ورفضَ قبلَ أن يصلَ شىءٌ إلى
-- المستودع. وهذا هو الغرضُ من كتابةِ الحرّاسِ أصلاً: **أن يُمسَكَ النقصُ على
-- كاتبِه لا على المستخدِم.**
--
-- ═══ والعلاجُ سطرٌ واحد ═══
--
-- ولا يُبرَّرُ الخطأُ بأنّ الضررَ صغير: دالّةُ الزنادِ **لا يستطيعُ أحدٌ نداءَها
-- مباشرةً** ولو مُنِحَت — فالضررُ هنا ليس ثغرةً بل **ادّعاءَ منحةٍ لا معنى لها**،
-- وهو بعينِه ما يمنعُه الفحص: أن يبقى فى القاعدةِ إذنٌ لا يُستعمَل. **ولا يُترَكُ
-- بابٌ مرسومٌ على الحائط.**
--
-- ولا يتغيّرُ سلوكُ الزنادِ بحرف: يُنزَعُ الإذنُ ويبقى المُشغِّلُ يعملُ كما وُلد،
-- **لأنّ المُشغِّلاتِ تجرى بحقِّ الجدولِ لا بحقِّ المُنادى**.
-- ═══════════════════════════════════════════════════════════════════════════

REVOKE ALL ON FUNCTION public.enforce_payment_reference_resolves() FROM PUBLIC, anon, authenticated;

-- والبرهانُ فورىّ: الفحصانِ اللذانِ رفضا يُنادَيانِ الآن، فإن سقطَ أحدُهما
-- سقطتِ الهجرةُ ولم يُكتَبْ شىء.
SELECT public.assert_baseline_v3_75_25_check();
SELECT public.assert_baseline_v3_75_29_check();
SELECT public.assert_baseline_v3_75_44_check();
