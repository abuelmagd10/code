-- v3.74.969 — مدفوعاتُ المورّدين تدخل القاعدة، وتحصيلُ البيع يبقى خارجَها
-- ============================================================================
-- فى ٩٦٦ استثنيتُ جدولَ المدفوعات كلَّه من قاعدة «مَن كتب لا يوقّع»، لأنّى
-- قِستُ فوجدتُ أنّ خانةَ «مَن اعتمد» تُملأ لحظةَ الإنشاء فى ١٤ صفّاً من ٢٠ —
-- أى أنّها خَتمٌ آلىٌّ لا قرارُ إنسان. ولو ربطتُ الحارسَ لتعطّل الإنشاء.
--
-- **وصحّح المالكُ التأطير**: قال إنّ مدفوعاتِ فواتير البيع هى التى بلا اعتماد،
-- وأنّ ذلك **مقصود**. فأعدتُ القياسَ مفصولاً، فإذا الأمرُ كما قال حرفاً:
--
--   تحصيلُ عميل (بيع):   ٢٥ صفّاً · ١٣ خُتمت لحظةَ الإنشاء · ٠ اعتُمدت لاحقاً
--                        · و٩ منها نفسُ الشخص → لا اعتمادَ فيها بحكم التصميم.
--   مدفوعةُ مورّد (شراء): ١١ صفّاً · ١ فقط خُتم لحظةَ الإنشاء · ٦ اعتُمدت لاحقاً
--                        · و**صفرُ** حالةٍ اعتمد فيها المُنشئُ نفسَه.
--
-- فالاستثناءُ كان أوسعَ ممّا يجب: الصوابُ أن تدخل **مدفوعاتُ المورّدين** فى
-- الحماية، ويبقى **تحصيلُ البيع** خارجَها.
--
-- والتنفيذُ لا يحتاج دالّةً جديدة: مُشغِّلٌ بشرط (WHEN) على نفس البيت الواحد
-- public.erp_sod_guard، يعمل حين يكون للمدفوعة مورّد.
--
-- وأثرُ التطبيق على البيانات القائمة: **صفرُ صفوفٍ** تصير مخالفة.
--
-- وأُثبت على قاعدة الاختبار فى ثلاثة اتّجاهات:
--   تحصيلُ عميلٍ بنفس الشخص      → يمرّ (لم يُمسّ).
--   مدفوعةُ مورّدٍ بشخصين مختلفين → لا يرفضها حارسُنا.
--   مدفوعةُ مورّدٍ بنفس الشخص     → يرفضها حارسُنا بالنصّ العربى.
--
-- وبقيت خارجَ القاعدة عن قصدٍ ومَقيسٍ أيضاً:
--   • القيودُ المحاسبية: كلُّ صفوفها الـ١٣٣ لها مرجعٌ إلى مستندٍ آخر، ولا صفَّ
--     واحداً «رُحِّل لاحقاً» بقرارِ شخصٍ ثانٍ. فهى **نتيجةٌ لا قرار**،
--     والضبطُ محلُّه المستندُ الذى وَلَدها.
--   • فواتيرُ البيع: ٢١ صفّاً كلُّها معتمَدةٌ لحظةَ الإنشاء — البيعُ عملٌ
--     يومىٌّ لا يحتاج توقيعاً ثانياً، كما قرّر المالك.
-- ============================================================================

BEGIN;

DROP TRIGGER IF EXISTS aa_erp_sod_guard ON public.payments;
CREATE TRIGGER aa_erp_sod_guard
  BEFORE INSERT OR UPDATE ON public.payments
  FOR EACH ROW
  WHEN (NEW.supplier_id IS NOT NULL)
  EXECUTE FUNCTION public.erp_sod_guard('created_by|approved_by|مُعتَمِدُ مدفوعةِ المورّد لا يَجوزُ أن يكون هو نفسَه مُنشِئَها.');

DO $do$
DECLARE v_n int; v_when text;
BEGIN
  SELECT count(*) INTO v_n FROM pg_trigger tg JOIN pg_proc p ON p.oid=tg.tgfoid
    JOIN pg_namespace n ON n.oid=p.pronamespace
   WHERE NOT tg.tgisinternal AND n.nspname='public' AND p.proname='erp_sod_guard';
  IF v_n <> 27 THEN RAISE EXCEPTION 'v3.74.969: المتوقَّع ٢٧ مُشغِّلاً والموجود %.', v_n; END IF;

  SELECT pg_get_triggerdef(tg.oid) INTO v_when
    FROM pg_trigger tg JOIN pg_class c ON c.oid=tg.tgrelid
    JOIN pg_namespace n ON n.oid=c.relnamespace
   WHERE n.nspname='public' AND c.relname='payments' AND tg.tgname='aa_erp_sod_guard';
  IF v_when IS NULL OR v_when NOT LIKE '%supplier_id IS NOT NULL%' THEN
    RAISE EXCEPTION 'v3.74.969: مُشغِّلُ المدفوعات بلا شرطِ المورّد — سيمسّ تحصيلَ البيع.';
  END IF;
END
$do$;

COMMIT;
