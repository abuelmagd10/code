type SupabaseLike = any

/**
 * يكتب سطراً فى `audit_logs` ويُبلّغ عند الفشل.
 *
 * **لا يرمى أبداً.** فشلُ التسجيل لا يُبطل العملية التى يسجّلها.
 *
 * @param client عميل supabase (مُصادَق أو خدمى — كما هو فى موضع الاستدعاء).
 * @param row    الصف كما كان يُمرَّر إلى `.insert()` تماماً.
 * @param context اسم الموضع، ليظهر فى السجل فيُعرف مصدر الفشل بلا بحث.
 * @returns true إذا كُتب السطر.
 */
export async function writeAuditLog(
  client: SupabaseLike,
  row: Record<string, unknown> | Array<Record<string, unknown>>,
  context: string
): Promise<boolean> {
  try {
    const { error } = await client.from("audit_logs").insert(row as any)

    if (error) {
      const first = Array.isArray(row) ? row[0] : row
      console.error(
        `AUDIT_LOG_WRITE_FAILED [${context}]: ` +
        `action=${String(first?.action ?? "?")} ` +
        `entity=${String(first?.entity ?? "?")} ` +
        `entity_id=${String(first?.entity_id ?? "?")} ` +
        `company=${String(first?.company_id ?? "?")} — ${error.message}`
      )
      return false
    }

    return true
  } catch (thrown: any) {
    // supabase-js لا يرمى على فشل الكتابة، لكن انقطاع الشبكة أو خطأً فى
    // العميل نفسه قد يرمى. ويُلتقط هنا كى لا يُبطل التسجيلُ عمليةً نجحت.
    console.error(
      `AUDIT_LOG_WRITE_THREW [${context}]: ${thrown?.message || String(thrown)}`
    )
    return false
  }
}
